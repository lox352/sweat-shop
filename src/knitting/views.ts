import type { Held } from "./needles";
import { type MarkerLine, startLine } from "./view";

/**
 * The chart's views: which of the sweater's stitches one chart shows.
 *
 * A stitch is drawn over the stitches it was worked into, so a chart is a
 * family tree, and most stitches have one place in it. The underarm's cast-on
 * stitches have two. The body knits on from them, and the sleeve picks up out
 * of them on the other side of the same edge, so they are the bottom of two
 * pieces at once, which no one chart can stand both of on. So the sweater has
 * more than one chart. Each is a view of the stitches, generated by a row of
 * them: that row, everything it was worked out of, and everything worked out
 * of it.
 *
 * The row is what is on the needles at a moment the needles change: as the
 * knitting begins, as stitches go on hold, and as held stitches are taken up
 * again. So the chart the knitting is on is always what the needles hold, and
 * where it comes from, and where it goes:
 *
 * - The first is generated by the cast-on. It shows the yoke, and above it
 *   most of the body and most of each sleeve: everything but the underarms.
 * - Putting stitches on hold, and casting on any number in their place,
 *   generates the next: what is left on the needles, the cast-on stitches
 *   among them. The held stitches are no longer live, so they leave the
 *   chart, with the stitches below them they alone were worked out of, and
 *   with all that will be knitted from them. The stitches still to be held
 *   later in the round are live yet, and stay, with what is knitted from
 *   them: between a sweater's two sleeves going on hold, its chart is the
 *   body and the second sleeve, over the yoke but for the first sleeve. Once
 *   the last of them is held it is the body's view: the body, both underarms
 *   and most of the yoke.
 * - Taking held stitches up again generates a sleeve's view: the held
 *   stitches with the cast-on ones after them, reversed, as the piece that
 *   takes them up goes round them - its underarm and the whole sleeve, each
 *   stitch picked up out of the cast-on standing over the stitch it came out
 *   of.
 *
 * The views of a finished pattern are those once the knitting has played
 * through: the first, the last of a round's holds, and the sleeves'. A hold
 * before the last of its round only gives a stage on the way to the last,
 * the chart the knitting is on until the round is through.
 *
 * All of it is worked out from the stitches in order, with nothing that comes
 * after: a view begins at the step that generates it, and a stitch is in it
 * from the moment it is made, by what it was worked into. Only what a view's
 * row was worked out of is filled in as the row is knitted.
 */
export interface ChartView {
  id: string;
  kind: "neck" | "remaining" | "held";
  /** What the knitting calls it: "From the neck", "Body", "Right sleeve". */
  label: string;
  /** For a held view, the holder whose stitches generate it. */
  holder?: string;
  /** The row that generates it, in the order its stitches are on the chart. */
  generator: number[];
  /** Its stitches: the generator, what that was worked out of, and what is worked out of it. */
  members: Set<number>;
  /** The step or stitch it is made at: the hold, for a sleeve's, which it waits on to be taken up. */
  createdAt: number;
  /** Where the knitting comes to it: the first stitch after the step that generates it, and never, for one not taken up yet. */
  begins: number;
  /**
   * For a stage on the way to another, as stitches go on hold one lot after
   * another in a round: the view of the finished round it leads to, whose
   * tab it is shown under while the knitting is at it.
   */
  stageOf?: string;
}

interface Built {
  stitches: Stitch[];
  holds: Held[];
  knitting: { rounds: number[][]; roundPieces: string[] };
}

/** The stitches of the round below that this one is worked into. */
const worksInto = (stitch: Stitch): number[] => stitch.links.slice(0, consumption[stitch.type]);

/**
 * A make-one is worked into nothing below it, only the bar between two
 * stitches: it belongs with the stitch it is worked after, the yarn's last,
 * as its loops are side by side on the needle.
 */
const madeBeside = (stitch: Stitch): number | undefined =>
  stitch.type === "m1" ? stitch.links[stitch.links.length - 1] : undefined;

/**
 * Everything worked out of `from`, from the stitch `start` on: each stitch
 * worked into one of them, or made beside one. Stitches are in the order
 * they are worked, so a stitch's parents always come before it. Never through
 * `blocked`, a held view's cast-on stitches, which the body knits on from on
 * their other side; picked up out of `edge` instead.
 */
const descendants = (
  stitches: Stitch[],
  from: Set<number>,
  start: number,
  blocked: Set<number> = new Set(),
  edge: Set<number> = new Set(),
): Set<number> => {
  const out = new Set(from);
  const through = (id: number) => out.has(id) && !blocked.has(id);
  for (let id = start; id < stitches.length; id++) {
    const stitch = stitches[id];
    if (out.has(id) || !isFabric(stitch)) continue;
    if (stitch.type === "pickUp") {
      if (stitch.from !== undefined && edge.has(stitch.from)) out.add(id);
      continue;
    }
    const beside = madeBeside(stitch);
    if ((beside !== undefined && through(beside)) || worksInto(stitch).some(through)) out.add(id);
  }
  return out;
};

/** And everything they were worked out of, adding to `into`. */
const ancestors = (stitches: Stitch[], from: Iterable<number>, into: Set<number>) => {
  const waiting = [...from];
  while (waiting.length > 0) {
    const stitch = stitches[waiting.pop()!];
    if (!stitch) continue;
    for (const below of worksInto(stitch)) {
      if (into.has(below) || !isFabric(stitches[below])) continue;
      into.add(below);
      waiting.push(below);
    }
  }
};

/** The fabric stitch after a step. */
const fabricAfter = (stitches: Stitch[], id: number): number => {
  let at = id + 1;
  while (at < stitches.length && isStep(stitches[at])) at++;
  return at;
};

/** And before it. */
const fabricBefore = (stitches: Stitch[], id: number): number => {
  let at = id - 1;
  while (at > 0 && isStep(stitches[at])) at--;
  return at;
};

const views = new WeakMap<Stitch[], ChartView[]>();

/** A sweater's views, in the order the knitting comes to them: see ChartView. */
export const chartViews = (built: Built, pieces: { id: string; label: string }[] = []): ChartView[] => {
  const known = views.get(built.stitches);
  if (known) return known;
  const { stitches, holds, knitting } = built;
  const labelOf = (piece: string) => pieces.find((one) => one.id === piece)?.label ?? piece;
  const roundOf = new Map<number, number>();
  knitting.rounds.forEach((round, index) => round.forEach((id) => roundOf.set(id, index)));

  const found: ChartView[] = [];
  const cast = (knitting.rounds[0] ?? []).filter((id) => isFabric(stitches[id]));
  if (cast.length > 0) {
    const members = descendants(stitches, new Set(cast), cast[0]);
    found.push({ id: "neck", kind: "neck", label: "From the neck", generator: cast, members, createdAt: cast[0], begins: cast[0] });
  }

  /*
   * What is on the needles once a hold and its cast-on are done: replayed,
   * every stitch made taking the place of those it was worked into, every
   * hold taking its stitches off, and every taking up putting them back.
   */
  // The stitches each step put on hold: a block may be held a part at a time (see Needles.hold).
  const partAt = new Map<number, number[]>();
  for (const held of holds) for (const part of held.parts ?? [{ at: held.heldAt, stitches: held.stitches }]) partAt.set(part.at, part.stitches);
  const liveAfter = (last: number): number[] => {
    const live = new Set<number>();
    for (let id = 0; id <= last && id < stitches.length; id++) {
      const stitch = stitches[id];
      if (stitch.type === "hold") {
        for (const one of partAt.get(id) ?? []) live.delete(one);
        continue;
      }
      if (stitch.type === "resume") {
        for (const one of holds.find((held) => held.holder === stitch.holder)?.stitches ?? []) live.add(one);
        continue;
      }
      if (!isFabric(stitch)) continue;
      for (const below of worksInto(stitch)) live.delete(below);
      if (!boundOff(stitch.type)) live.add(id);
    }
    return [...live].sort((a, b) => a - b);
  };
  const resumedAt = (holder: string): number | undefined =>
    stitches.find((stitch) => stitch.type === "resume" && stitch.holder === holder)?.id;

  const stages: ChartView[] = [];
  const sleeves: ChartView[] = [];
  // Every step that put stitches on hold, in the order worked, with the holder it put them under.
  const steps = holds
    .flatMap((held) => (held.parts ?? [{ at: held.heldAt, stitches: held.stitches }]).map((part) => ({ at: part.at, held })))
    .sort((a, b) => a.at - b.at);
  const roundAt = (step: number) => roundOf.get(fabricAfter(stitches, step)) ?? roundOf.get(fabricBefore(stitches, step));
  steps.forEach(({ at, held }, k) => {
    const after = fabricAfter(stitches, at);
    const round = roundAt(at);
    if (round === undefined) return;
    /*
     * What is on the needles once it is held and the stitches cast on in its
     * place are: the whole run of them straight after it, markers among them,
     * with any one more cast on to be passed over the next stitch and close
     * it up.
     */
    let cast = at;
    while (stitches[cast + 1] && (stitches[cast + 1].type === "castOn" || stitches[cast + 1].type === "marker")) cast++;
    const generator = liveAfter(cast);
    const members = descendants(stitches, new Set(generator), generator[0] ?? after);
    ancestors(stitches, generator, members);
    const next = steps[k + 1];
    stages.push({
      id: `remaining-${at}`,
      kind: "remaining",
      label: labelOf(stitches[after]?.piece ?? held.holder),
      generator,
      members,
      createdAt: at,
      begins: at + 1,
      // A stage on the way to the next step's, where another holds stitches in the same round.
      ...(next && roundAt(next.at) === round ? { stageOf: `remaining-${next.at}` } : {}),
    });
  });
  for (const held of holds) {
    const edge = held.edge ?? [];
    const generator = [...held.stitches, ...[...edge].reverse()];
    const members = descendants(stitches, new Set(generator), Math.min(...held.stitches), new Set(edge), new Set(edge));
    ancestors(stitches, held.stitches, members);
    const resumed = resumedAt(held.holder);
    sleeves.push({
      id: `held-${held.holder}`,
      kind: "held",
      label: labelOf(held.holder),
      holder: held.holder,
      generator,
      members,
      createdAt: held.heldAt,
      begins: resumed === undefined ? Infinity : resumed + 1,
    });
  }
  // A stage leads to the last of its round's: each on to the next, and so to the last.
  for (const stage of stages) {
    let to = stage.stageOf;
    while (to) {
      const next = stages.find((one) => one.id === to);
      if (!next?.stageOf) break;
      to = next.stageOf;
    }
    if (to) stage.stageOf = to;
  }
  found.push(...stages, ...sleeves);
  views.set(stitches, found);
  return found;
};

const following = new WeakMap<ChartView[], Int16Array>();

/**
 * The view the knitting is in at each stitch, by its id: the one generated
 * by the last change of the needles before it - the cast-on, a hold, a
 * taking up. So the first stitch after a sleeve goes on hold is on the chart
 * of what is left on the needles, and the first stitch a sleeve picks up is
 * on the sleeve's. A hold or a taking up is itself in the view of the stitch
 * before it: until it is done, the stitches it moves are still where they
 * were.
 */
export const viewsFollowed = (all: ChartView[], built: Pick<Built, "stitches">): Int16Array => {
  const known = following.get(all);
  if (known) return known;
  const { stitches } = built;
  const at = new Int16Array(stitches.length);
  // The views in the order the knitting comes to them.
  const order = all.map((view, index) => ({ begins: view.begins, index })).sort((a, b) => a.begins - b.begins);
  let next = 0;
  let current = 0;
  for (let id = 0; id < stitches.length; id++) {
    while (next < order.length && order[next].begins <= id) current = order[next++].index;
    at[id] = current;
  }
  following.set(all, at);
  return at;
};

/** The view the knitting is in once `progress` stitches are worked: the next stitch's. */
export const viewFollowedAt = (all: ChartView[], built: Pick<Built, "stitches">, progress: number): number => {
  const at = viewsFollowed(all, built);
  return at[Math.min(Math.max(progress + 1, 0), at.length - 1)] ?? 0;
};

/**
 * A view's chart: the sweater's chart, as the knitting counts it, with only
 * the view's stitches on it, and the columns none of them is in taken out.
 * Every stitch keeps its row and its round, so the rows are numbered and
 * named alike on every view.
 *
 * A held view's cast-on stitches go down beside the held stitches, in the
 * row that generates it, each under the stitch picked up out of it, and the
 * columns turn so the piece's own round begins at the right-hand edge.
 * Where more stitches are picked up out of the corners than the edge has, the
 * extra ones stand beside, over nothing, as a make-one does.
 */
export const layOutView = (
  view: ChartView,
  layout: ChartLayout,
  built: Pick<Built, "stitches">,
  edge: number[] = [],
): {
  layout: ChartLayout;
  column: (column: number) => number | undefined;
  /** Where the boundary to the left of a column of the sweater's chart is on the view's, if inside it. */
  boundary: (after: number) => number | undefined;
} => {
  const { stitches } = built;
  const cells = new Map<number, Cell>();
  for (const id of view.members) {
    const cell = layout.cells.get(id);
    if (cell) cells.set(id, cell);
  }

  let start: number | undefined;
  if (view.kind === "held" && edge.length > 0) {
    const heldIds = view.generator.filter((id) => !edge.includes(id));
    const heldRow = layout.cells.get(heldIds[heldIds.length - 1])?.row;
    const edgeSet = new Set(edge);
    // The stitch picked up out of each: of more than one out of a corner, the one furthest from the corner.
    const over = new Map<number, number>();
    let pickUps: number | undefined;
    let pastHeld = false;
    for (const id of [...view.members].sort((a, b) => a - b)) {
      const stitch = stitches[id];
      if (stitch.type === "pickUp" && stitch.from !== undefined && edgeSet.has(stitch.from)) {
        pickUps ??= id;
        if (pastHeld || !over.has(stitch.from)) over.set(stitch.from, id);
      } else if (pickUps !== undefined && id > pickUps) {
        pastHeld = true;
      }
    }
    // Without any picked up yet, in their own columns, the other way round.
    const ownColumns = edge.map((id) => layout.cells.get(id)?.column ?? 0).sort((a, b) => b - a);
    edge.forEach((id, k) => {
      const cell = layout.cells.get(id);
      if (!cell) return;
      const above = over.get(id);
      const column = above !== undefined ? layout.cells.get(above)?.column : ownColumns[k];
      cells.set(id, { ...cell, row: heldRow ?? cell.row, column: column ?? cell.column });
    });
    start = pickUps ?? heldIds[0];
  }

  // The columns any of its stitches are in, renumbered in order from 1.
  const kept = new Set<number>();
  for (const cell of cells.values()) {
    const whole = Math.floor(cell.column);
    kept.add(whole);
    if (cell.column > whole && whole + 1 <= layout.columns) kept.add(whole + 1);
  }
  const order = [...kept].sort((a, b) => a - b);
  const renumbered = new Map(order.map((column, k) => [column, k + 1]));
  const width = order.length;
  const startAt = start === undefined ? undefined : cells.get(start)?.column;
  const first = startAt === undefined ? 1 : (renumbered.get(Math.floor(startAt)) ?? 1);
  const turn = (column: number) => ((((column - first) % width) + width) % width) + 1;
  const column = (at: number): number | undefined => {
    const whole = renumbered.get(Math.floor(at));
    return whole === undefined ? undefined : turn(whole + (at - Math.floor(at)));
  };

  let rows = 0;
  for (const [id, cell] of cells) {
    cells.set(id, { ...cell, column: column(cell.column) ?? cell.column });
    rows = Math.max(rows, cell.row);
  }
  // The boundary to the left of a column, by the columns kept at or to the right of it.
  const boundary = (after: number): number | undefined => {
    let low = 0;
    let high = order.length;
    while (low < high) {
      const k = (low + high) >> 1;
      if (order[k] <= after) low = k + 1;
      else high = k;
    }
    return low === 0 || low === width ? undefined : turn(low);
  };
  return { layout: { cells, rows, columns: width, roundRows: layout.roundRows }, column, boundary };
};

/**
 * The marker lines on a view's chart: each between the columns it stands
 * between there, or where those columns would be when one side is not in it.
 */
export const markersInView = (
  lines: MarkerLine[],
  boundary: (after: number) => number | undefined,
  /** Where a column of the sweater's chart is on the view's, if in it: for a start of the round, beside its rounds' first stitches. */
  column: (column: number) => number | undefined = () => undefined,
): MarkerLine[] =>
  lines.flatMap((line) => {
    if (line.edge) {
      // At the chart's far edge, to the left of the stitch before it there: wherever the view has that column, beside it.
      const rows = line.route.flatMap((row) => {
        const at = column(row.after);
        return at === undefined ? [] : [{ ...row, after: Math.round(at) }];
      });
      if (rows.length === 0) return [];
      const after = Math.max(...rows.map((row) => row.after));
      const route = rows.map((row) => ({ ...row, after }));
      return [{ ...line, after, from: route[0].row, to: route[route.length - 1].row, route }];
    }
    if (line.atStart) {
      // Beside the first stitch of each of its rows the view has, at the edge of the view if that is where they are.
      const rows = line.route.flatMap((row) => {
        const beside = row.beside === undefined ? undefined : column(row.beside);
        return beside === undefined ? [] : [{ ...row, beside: Math.round(beside) }];
      });
      if (rows.length === 0) return [];
      const route = startLine(rows);
      return [{ ...line, after: route[0].after, from: route[0].row, to: route[route.length - 1].row, route }];
    }
    const after = boundary(line.after);
    if (after === undefined) return [];
    const route = line.route.flatMap((row) => {
      const at = boundary(row.after);
      return at === undefined ? [] : [{ ...row, after: at }];
    });
    return [{ ...line, after, route }];
  });
